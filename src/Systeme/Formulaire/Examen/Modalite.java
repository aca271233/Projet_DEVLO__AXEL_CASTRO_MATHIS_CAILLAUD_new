package Systeme.Formulaire.Examen;

/**
 * Cette enumeration represente la lise des modalites differents que l'on peut retrouver pour une epreuve.
 * @author axel
 */
public enum Modalite {
    /**
     * Examen écrit
     */
    ExamenEcrit,

    /**
     * Examen oral
     */
    Oral,

    /**
     * Examen questionnaire a choix multiples
     */
    QCM,

    /**
     * Examen sur ordinateur
     */
    SurOrdinateur,

    /**
     * Examen sur projet
     */
    Projet,

    /**
     * Examen en travaux pratiques
     */
    TP
}
